    void CreateMaterial(PS1BlobShadow first)
    {
        Shader sh = Shader.Find("Shader Graphs/PS1_BlobShadow");
        if (sh == null)
        {
            UnityEditor.EditorUtility.DisplayDialog("PS1 Blob Shadow",
                "Couldn't find the shader 'Shader Graphs/PS1_BlobShadow'.\n\nMake sure PS1_BlobShadow.shadergraph is in your project " +
                "and imported without errors.", "OK");
            return;
        }

        string dir = "Assets";
        UnityEditor.MonoScript script = UnityEditor.MonoScript.FromMonoBehaviour(first);
        if (script != null)
        {
