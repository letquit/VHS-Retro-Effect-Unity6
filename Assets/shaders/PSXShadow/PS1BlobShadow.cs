using System.Collections.Generic;
using UnityEngine;
using UnityEngine.SceneManagement;

/// <summary>
/// PS1 / N64 style dithered blob shadow.
/// Add this to any object. It spawns a quad under it, snaps it to the ground, tilts it to the
/// surface normal (clamped so it never stands up on sharp edges), and sizes it from the
/// object's renderers. Every automatic value can be overridden in the inspector.
///
/// Works in Edit mode too: the shadow shows in the Scene and Game view and updates live while you
/// change values in the Inspector or move the object. The status box at the top of the component
/// tells you why a shadow isn't showing.
///
/// Needs a material that uses the "PS1_BlobShadow" Shader Graph.
/// </summary>
[ExecuteAlways]
[DisallowMultipleComponent]
[AddComponentMenu("Rendering/PS1 Blob Shadow")]
public class PS1BlobShadow : MonoBehaviour
{
    public enum DitherPattern
    {
        Bayer4x4_BuiltIn = 0,
        Bayer2x2 = 1,
        Bayer8x8 = 2,
        Bayer16x16 = 3,
        CustomTexture = 4,
    }

    public enum SizeMode { Auto, Manual }

    // ------------------------------------------------------------------ Material
    [Header("Material")]
    [Tooltip("A material using the PS1_BlobShadow shader graph. Each shadow gets its own instance, so the original is never modified.")]
    public Material shadowMaterial;
    public Color shadowColor = Color.black;
    [Range(0f, 1f), Tooltip("1 = solid core. Lower values thin the dither out (0.5 = checkerboard-ish halftone).")]
    public float opacity = 1f;
    [Range(0.25f, 10f), Tooltip("Higher = bigger solid core and a thinner dithered rim. Lower = long gradient from the middle.")]
    public float edgeFalloff = 3f;

    // ------------------------------------------------------------------ Dither
    [Header("Dither")]
    [Tooltip("Bayer4x4_BuiltIn uses Unity's Dither node. The other Bayer sizes are generated by this script. CustomTexture uses Custom Pattern below.")]
    public DitherPattern pattern = DitherPattern.Bayer4x4_BuiltIn;
    [Tooltip("Square grayscale threshold texture (4x4, 8x8, 64x64 blue noise...). Import with: sRGB OFF, Compression None, " +
             "Filter Point, Wrap Repeat, no mipmaps. Darker texel = pixel appears sooner.")]
    public Texture2D customPattern;
    [Min(0.25f), Tooltip("Size of one dither dot in screen pixels. 1 = finest, 3-4 = chunky retro.")]
    public float ditherScale = 3f;

    // ------------------------------------------------------------------ Size
    [Header("Size")]
    [Tooltip("Auto = guess from the renderers on this object and its children. Manual = use Manual Size.")]
    public SizeMode sizeMode = SizeMode.Auto;
    [Min(0.01f), Tooltip("Auto mode: multiplies the guessed footprint.")]
    public float autoSizeMultiplier = 1.25f;
    [Tooltip("Use the longer side for both axes (round shadow).")]
    public bool forceCircle = false;
    [Tooltip("Manual mode: shadow width (X) and length (Z) in world units.")]
    public Vector2 manualSize = new Vector2(1f, 1f);
    [Tooltip("Rotate the shadow with the object's heading, so long objects get a long shadow in the right direction.")]
    public bool followObjectYaw = true;
    [Tooltip("Shift the shadow (in the shadow's own X/Z) from its computed center.")]
    public Vector2 offset = Vector2.zero;
    [Tooltip("Optional. If set, only these renderers are used for the auto-size guess (e.g. just the body mesh).")]
    public Renderer[] customBoundsRenderers;

    // ------------------------------------------------------------------ Ground / height
    [Header("Ground / Height")]
    public LayerMask groundMask = ~0;
    [Min(0.1f), Tooltip("How far below the object to look for ground. No ground = no shadow.")]
    public float maxDistance = 30f;
    [Tooltip("The ray starts this far above the object's pivot, so objects standing in the floor still hit it.")]
    public float rayStartOffset = 0.25f;
    public QueryTriggerInteraction triggerInteraction = QueryTriggerInteraction.Ignore;
    [Tooltip("Lift above the surface along its normal. Raise this if you see z-fighting.")]
    public float heightOffset = 0.02f;
    [Tooltip("Skip raycasting and put the shadow on a fixed world height (flat floors, no colliders).")]
    public bool useFixedGroundHeight = false;
    public float fixedGroundY = 0f;
    [Tooltip("Hide the shadow when nothing is below. If off, it stays where it last was.")]
    public bool hideWhenNoGround = true;

    // ------------------------------------------------------------------ Orientation
    [Header("Orientation")]
    [Tooltip("Tilt the shadow to match the surface below.")]
    public bool alignToSurface = true;
    [Range(0f, 89f), Tooltip("The shadow never tilts more than this away from flat. Stops it standing up on walls and sharp edges.")]
    public float maxTiltAngle = 45f;
    [Min(0f), Tooltip("How fast the tilt follows the ground in Play mode. 0 = instant snap (very N64).")]
    public float alignSpeed = 14f;

    // ------------------------------------------------------------------ Height response
    [Header("Height Response (jumping / falling)")]
    public bool shrinkWithHeight = true;
    public bool fadeWithHeight = true;
    [Min(0.1f), Tooltip("Height above ground (world units) that maps to 1.0 on the curves below.")]
    public float heightFalloffDistance = 6f;
    [Tooltip("Scale multiplier over height (X = 0..1 of the falloff distance).")]
    public AnimationCurve scaleByHeight = AnimationCurve.Linear(0f, 1f, 1f, 0.5f);
    [Tooltip("Opacity multiplier over height. With dither this thins the dots out.")]
    public AnimationCurve opacityByHeight = AnimationCurve.Linear(0f, 1f, 1f, 0.3f);

    // ------------------------------------------------------------------ Rendering
    [Header("Rendering")]
    [Tooltip("Layer of the spawned shadow object. 2 = Ignore Raycast.")]
    public int shadowLayer = 2;
    [Tooltip("Hide the spawned shadow object in the Hierarchy. Turn off to inspect it.")]
    public bool hideInHierarchy = true;

    // ------------------------------------------------------------------ status (read by the inspector)
    enum State { Starting, NoMaterial, NoGround, Active }

    public string Status
    {
        get
        {
            switch (_state)
            {
                case State.NoMaterial:
                    return "No shadow material. Assign a material that uses the PS1_BlobShadow shader graph " +
                           "(or press 'Create Material From Shader').";
                case State.NoGround:
                    return "No ground found within " + maxDistance.ToString("0.#") + " units below. Make sure the floor has a collider " +
                           "and is included in Ground Mask, or turn on Use Fixed Ground Height.";
                case State.Active:
                    return string.Format("Active  |  size {0:0.00} x {1:0.00}  |  {2:0.00} above ground",
                        _lastSize.x, _lastSize.y, _lastHeight);
                default:
                    return "Starting...";
            }
        }
    }

    public bool StatusIsWarning
    {
        get { return _state == State.NoMaterial || _state == State.NoGround; }
    }

    // ------------------------------------------------------------------ internals
    static readonly int ID_Color = Shader.PropertyToID("_ShadowColor");
    static readonly int ID_Opacity = Shader.PropertyToID("_Opacity");
    static readonly int ID_Falloff = Shader.PropertyToID("_EdgeFalloff");
    static readonly int ID_DitherScale = Shader.PropertyToID("_DitherScale");
    static readonly int ID_UsePattern = Shader.PropertyToID("_UsePatternTexture");
    static readonly int ID_Pattern = Shader.PropertyToID("_PatternTexture");
    static readonly int ID_PatternSize = Shader.PropertyToID("_PatternSize");

    const string FallbackShaderName = "Shader Graphs/PS1_BlobShadow";

    // Shared generated assets. Reference counted so nothing leaks between edit/play mode or recompiles.
    static Mesh s_Quad;
    static readonly Dictionary<int, Texture2D> s_Bayer = new Dictionary<int, Texture2D>();
    static int s_Users;

    GameObject _go;
    Transform _tf;
    MeshRenderer _renderer;
    Material _mat;
    Material _sourceMaterial;
    Renderer[] _renderers;
    readonly RaycastHit[] _hits = new RaycastHit[16];

    Vector3 _smoothedNormal = Vector3.up;
    bool _hasState;
    bool _registered;
    bool _loggedMissing;
    bool _dirty = true;
    float _heightFade = 1f;
    State _state = State.Starting;
    Vector2 _lastSize;
    float _lastHeight;

#if UNITY_EDITOR
    bool _refreshQueued;
    double _lastEditorUpdate;
    Vector3 _lastPos;
    Quaternion _lastRot;
    Vector3 _lastScale;
#endif

    struct Solution
    {
        public bool hasGround;
        public Vector3 point;
        public Vector3 normal;   // already clamped by maxTiltAngle
        public Vector2 size;
        public float height;
        public Quaternion frame;
    }

    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.SubsystemRegistration)]
    static void ResetStatics()
    {
        s_Quad = null;
        s_Bayer.Clear();
        s_Users = 0;
    }

    // ================================================================== lifecycle
    void OnEnable()
    {
        _loggedMissing = false;
        _dirty = true;
        RefreshRenderers();

        if (Application.isPlaying)
        {
            CreateShadow();
        }
#if UNITY_EDITOR
        else
        {
            UnityEditor.EditorApplication.update += EditorTick;
            QueueEditorRefresh(); // creating objects straight from OnEnable in edit mode is fragile, so defer
        }
#endif
    }

    void OnDisable()
    {
#if UNITY_EDITOR
        UnityEditor.EditorApplication.update -= EditorTick;
        UnityEditor.EditorApplication.delayCall -= EditorRefresh;
        _refreshQueued = false;
#endif
        DestroyShadow();
    }

    void OnValidate()
    {
        manualSize = Vector2.Max(manualSize, new Vector2(0.01f, 0.01f));
        shadowLayer = Mathf.Clamp(shadowLayer, 0, 31);
        _dirty = true;

        if (Application.isPlaying)
        {
            if (_go != null)
            {
                if (_sourceMaterial != shadowMaterial)
                {
                    DestroyShadow();
                    CreateShadow();
                }
                else
                {
                    _go.layer = shadowLayer;
                    _go.hideFlags = ShadowHideFlags();
                    ApplyMaterialSettings();
                }
            }
        }
#if UNITY_EDITOR
        else
        {
            QueueEditorRefresh();
        }
#endif
    }

    void LateUpdate()
    {
        if (!Application.isPlaying) return; // edit mode is driven by EditorTick
        if (_tf == null) return;
        UpdateShadow(false);
    }

#if UNITY_EDITOR
    // ---------------------------------------------------------------- edit-mode driver
    void QueueEditorRefresh()
    {
        _dirty = true;
        if (_refreshQueued) return;
        _refreshQueued = true;
        UnityEditor.EditorApplication.delayCall += EditorRefresh;
    }

    void EditorRefresh()
    {
        _refreshQueued = false;
        if (this == null || Application.isPlaying) return;
        if (UnityEditor.EditorApplication.isPlayingOrWillChangePlaymode) return;
        if (!isActiveAndEnabled || !gameObject.scene.IsValid()) return;

        if (_go != null && _sourceMaterial != shadowMaterial) DestroyShadow();

        if (_go == null)
        {
            if (!CreateShadow()) return;
        }
        else
        {
            _go.layer = shadowLayer;
            _go.hideFlags = ShadowHideFlags();
            ApplyMaterialSettings();
        }

        _renderers = GatherRenderers();
        UpdateShadow(true);
        RepaintEditorViews();
    }

    void EditorTick()
    {
        if (this == null)
        {
            UnityEditor.EditorApplication.update -= EditorTick;
            return;
        }
        if (Application.isPlaying) return;
        if (UnityEditor.EditorApplication.isPlayingOrWillChangePlaymode) return;
        if (!isActiveAndEnabled || _go == null) return;

        Transform t = transform;
        bool moved = t.position != _lastPos || t.rotation != _lastRot || t.lossyScale != _lastScale;
        double now = UnityEditor.EditorApplication.timeSinceStartup;
        // Update when the object moved, a value changed, or every quarter second (catches moved ground / edited children).
        if (!_dirty && !moved && now - _lastEditorUpdate < 0.25) return;

        _dirty = false;
        _lastEditorUpdate = now;
        _lastPos = t.position;
        _lastRot = t.rotation;
        _lastScale = t.lossyScale;

        _renderers = GatherRenderers();
        UpdateShadow(true);
        RepaintEditorViews();
    }

    static void RepaintEditorViews()
    {
        UnityEditor.SceneView.RepaintAll();
        UnityEditor.EditorApplication.QueuePlayerLoopUpdate(); // refreshes the Game view while not playing
    }
#endif

    // ================================================================== per-frame update
    void UpdateShadow(bool instant)
    {
        if (_tf == null) return;

        Solution s;
        Solve(out s);

        if (!s.hasGround)
        {
            _state = State.NoGround;
            if (hideWhenNoGround) SetVisible(false);
            return;
        }

        if (instant || !_hasState || alignSpeed <= 0f)
            _smoothedNormal = s.normal;
        else
            _smoothedNormal = Vector3.Slerp(_smoothedNormal, s.normal, 1f - Mathf.Exp(-alignSpeed * Time.deltaTime)).normalized;

        Quaternion rot = Quaternion.FromToRotation(Vector3.up, _smoothedNormal) * s.frame;
        Vector3 pos = s.point + _smoothedNormal * heightOffset;

        float t = Mathf.Clamp01(s.height / Mathf.Max(0.0001f, heightFalloffDistance));
        float scaleMul = shrinkWithHeight ? Mathf.Max(0.01f, scaleByHeight.Evaluate(t)) : 1f;
        _heightFade = fadeWithHeight ? Mathf.Clamp01(opacityByHeight.Evaluate(t)) : 1f;

        _tf.SetPositionAndRotation(pos, rot);
        _tf.localScale = new Vector3(s.size.x * scaleMul, 1f, s.size.y * scaleMul);
        _mat.SetFloat(ID_Opacity, opacity * _heightFade);

        SetVisible(true);
        _hasState = true;
        _state = State.Active;
        _lastSize = s.size;
        _lastHeight = s.height;
    }

    // ================================================================== solving
    void Solve(out Solution s)
    {
        s = new Solution();
        s.frame = GetYawFrame();

        Vector3 pivot = transform.position;
        Vector3 center = pivot;
        Vector2 size = manualSize;
        float bottomY = pivot.y;

        Vector3 bCenter; Vector2 bSize; float bMinY;
        if (ComputeFootprint(s.frame, out bCenter, out bSize, out bMinY))
        {
            bottomY = bMinY;
            if (sizeMode == SizeMode.Auto)
            {
                center = new Vector3(bCenter.x, pivot.y, bCenter.z);
                size = bSize * autoSizeMultiplier;
            }
        }

        if (forceCircle)
        {
            float m = Mathf.Max(size.x, size.y);
            size = new Vector2(m, m);
        }

        center += s.frame * new Vector3(offset.x, 0f, offset.y);
        s.size = Vector2.Max(size, new Vector2(0.01f, 0.01f));

        Vector3 hitPoint, hitNormal;
        if (!FindGround(center, out hitPoint, out hitNormal))
        {
            s.hasGround = false;
            return;
        }

        s.hasGround = true;
        s.point = hitPoint;
        s.normal = ClampNormal(alignToSurface ? hitNormal : Vector3.up);
        s.height = Mathf.Max(0f, bottomY - hitPoint.y);
    }

    bool FindGround(Vector3 center, out Vector3 point, out Vector3 normal)
    {
        if (useFixedGroundHeight)
        {
            point = new Vector3(center.x, fixedGroundY, center.z);
            normal = Vector3.up;
            return true;
        }

        if (!Application.isPlaying) Physics.SyncTransforms(); // edit mode: make sure colliders are where the Scene view shows them

        Vector3 origin = center + Vector3.up * rayStartOffset;
        int count = Physics.RaycastNonAlloc(origin, Vector3.down, _hits, maxDistance + rayStartOffset, groundMask, triggerInteraction);

        float best = float.MaxValue;
        int bestIndex = -1;
        for (int i = 0; i < count; i++)
        {
            RaycastHit h = _hits[i];
            if (h.collider == null) continue;
            if (h.collider.transform.IsChildOf(transform)) continue; // never shadow onto ourselves
            if (h.distance < best) { best = h.distance; bestIndex = i; }
        }

        if (bestIndex < 0)
        {
            point = center;
            normal = Vector3.up;
            return false;
        }

        point = _hits[bestIndex].point;
        normal = _hits[bestIndex].normal;
        return true;
    }

    Vector3 ClampNormal(Vector3 n)
    {
        n.Normalize();
        float angle = Vector3.Angle(Vector3.up, n);
        if (angle > maxTiltAngle && angle > 0.0001f)
            n = Vector3.Slerp(Vector3.up, n, maxTiltAngle / angle).normalized;
        return n;
    }

    Quaternion GetYawFrame()
    {
        if (!followObjectYaw) return Quaternion.identity;
        Vector3 f = Vector3.ProjectOnPlane(transform.forward, Vector3.up);
        if (f.sqrMagnitude < 1e-4f) f = Vector3.ProjectOnPlane(transform.up, Vector3.up);
        if (f.sqrMagnitude < 1e-4f) return Quaternion.identity;
        return Quaternion.LookRotation(f.normalized, Vector3.up);
    }

    /// <summary>
    /// Footprint of the object's renderers measured along the shadow's own X/Z axes (the yaw frame).
    /// </summary>
    bool ComputeFootprint(Quaternion frame, out Vector3 worldCenter, out Vector2 size, out float minWorldY)
    {
        worldCenter = transform.position;
        size = Vector2.zero;
        minWorldY = transform.position.y;

        Renderer[] list = _renderers ?? GatherRenderers();
        if (list == null || list.Length == 0) return false;

        Quaternion inv = Quaternion.Inverse(frame);
        Vector3 min = new Vector3(float.PositiveInfinity, float.PositiveInfinity, float.PositiveInfinity);
        Vector3 max = new Vector3(float.NegativeInfinity, float.NegativeInfinity, float.NegativeInfinity);
        float worldMinY = float.PositiveInfinity;
        bool any = false;

        for (int r = 0; r < list.Length; r++)
        {
            Renderer rend = list[r];
            if (rend == null || !rend.enabled || !rend.gameObject.activeInHierarchy) continue;
            if (rend is ParticleSystemRenderer || rend is TrailRenderer || rend is LineRenderer) continue;

            Bounds b;
            Matrix4x4 m;
#if UNITY_2021_2_OR_NEWER
            if (rend is SkinnedMeshRenderer)
            {
                b = rend.bounds;                 // world-space AABB (localBounds is root-bone relative)
                m = Matrix4x4.identity;
            }
            else
            {
                b = rend.localBounds;            // tight, rotates properly with the mesh
                m = rend.localToWorldMatrix;
            }
#else
            b = rend.bounds;
            m = Matrix4x4.identity;
#endif
            Vector3 c = b.center;
            Vector3 e = b.extents;
            for (int i = 0; i < 8; i++)
            {
                Vector3 corner = c + new Vector3(
                    (i & 1) == 0 ? -e.x : e.x,
                    (i & 2) == 0 ? -e.y : e.y,
                    (i & 4) == 0 ? -e.z : e.z);
                Vector3 w = m.MultiplyPoint3x4(corner);
                if (w.y < worldMinY) worldMinY = w.y;
                Vector3 q = inv * w;
                min = Vector3.Min(min, q);
                max = Vector3.Max(max, q);
                any = true;
            }
        }

        if (!any) return false;

        worldCenter = frame * ((min + max) * 0.5f);
        size = new Vector2(max.x - min.x, max.z - min.z);
        minWorldY = worldMinY;
        return true;
    }

    // ================================================================== public API
    /// <summary>Call after adding/removing child renderers at runtime.</summary>
    public void RefreshRenderers()
    {
        _renderers = GatherRenderers();
    }

    /// <summary>Destroys and recreates the shadow (also re-reads the renderers).</summary>
    public void ForceRebuild()
    {
        DestroyShadow();
        RefreshRenderers();
        _dirty = true;
        if (!isActiveAndEnabled) return;
        if (CreateShadow()) UpdateShadow(!Application.isPlaying);
    }

    Renderer[] GatherRenderers()
    {
        if (customBoundsRenderers != null && customBoundsRenderers.Length > 0) return customBoundsRenderers;
        return GetComponentsInChildren<Renderer>(true);
    }

    // ================================================================== shadow object
    HideFlags ShadowHideFlags()
    {
        HideFlags f = hideInHierarchy ? HideFlags.HideInHierarchy : HideFlags.None;
        if (!Application.isPlaying) f |= HideFlags.DontSave; // edit-mode preview must never be saved into the scene
        return f;
    }

    bool CreateShadow()
    {
        if (_go != null) return true;

        Material source = shadowMaterial;
        bool tempSource = false;
        if (source == null)
        {
            Shader sh = Shader.Find(FallbackShaderName);
            if (sh == null)
            {
                _state = State.NoMaterial;
                if (Application.isPlaying && !_loggedMissing)
                {
                    _loggedMissing = true;
                    Debug.LogError("[PS1BlobShadow] No shadow material assigned and shader '" + FallbackShaderName +
                                   "' wasn't found. Create a material from the PS1_BlobShadow shader graph and assign it.", this);
                }
                return false;
            }
            source = new Material(sh) { hideFlags = HideFlags.HideAndDontSave };
            tempSource = true;
            if (Application.isPlaying)
                Debug.LogWarning("[PS1BlobShadow] No material assigned, using a temporary one. Assign a material so the shader is included in builds.", this);
        }

        _mat = new Material(source)
        {
            name = "PS1 Blob Shadow (Instance)",
            hideFlags = HideFlags.HideAndDontSave
        };
        _sourceMaterial = shadowMaterial;
        if (tempSource) SafeDestroy(source);

        _go = new GameObject("Blob Shadow (" + gameObject.name + ")");
        _go.hideFlags = ShadowHideFlags();
        _go.layer = shadowLayer;

        try
        {
            if (gameObject.scene.IsValid() && gameObject.scene.isLoaded)
                SceneManager.MoveGameObjectToScene(_go, gameObject.scene);
        }
        catch (System.Exception)
        {
            // Not fatal: the shadow just stays in the active scene.
        }

        _tf = _go.transform;

        MeshFilter mf = _go.AddComponent<MeshFilter>();
        mf.sharedMesh = GetQuad();

        _renderer = _go.AddComponent<MeshRenderer>();
        _renderer.sharedMaterial = _mat;
        _renderer.shadowCastingMode = UnityEngine.Rendering.ShadowCastingMode.Off;
        _renderer.receiveShadows = false;
        _renderer.lightProbeUsage = UnityEngine.Rendering.LightProbeUsage.Off;
        _renderer.reflectionProbeUsage = UnityEngine.Rendering.ReflectionProbeUsage.Off;
        _renderer.motionVectorGenerationMode = MotionVectorGenerationMode.ForceNoMotion;
        _renderer.enabled = false; // shown after the first successful solve

#if UNITY_EDITOR
        UnityEditor.SceneVisibilityManager.instance.DisablePicking(_go, true); // don't let clicks in the Scene view grab the shadow
#endif

        _registered = true;
        s_Users++;

        _hasState = false;
        _smoothedNormal = Vector3.up;
        _heightFade = 1f;
        _state = State.Starting;
        ApplyMaterialSettings();
        return true;
    }

    void DestroyShadow()
    {
        if (_go != null) SafeDestroy(_go);
        if (_mat != null) SafeDestroy(_mat);
        _go = null;
        _tf = null;
        _renderer = null;
        _mat = null;
        _sourceMaterial = null;
        _hasState = false;

        if (_registered)
        {
            _registered = false;
            s_Users = Mathf.Max(0, s_Users - 1);
            if (s_Users == 0) DestroyStatics();
        }
    }

    static void DestroyStatics()
    {
        if (s_Quad != null) SafeDestroy(s_Quad);
        s_Quad = null;
        foreach (KeyValuePair<int, Texture2D> kv in s_Bayer)
            if (kv.Value != null) SafeDestroy(kv.Value);
        s_Bayer.Clear();
    }

    static void SafeDestroy(Object o)
    {
        if (Application.isPlaying) Destroy(o);
        else DestroyImmediate(o);
    }

    void SetVisible(bool visible)
    {
        if (_renderer != null && _renderer.enabled != visible) _renderer.enabled = visible;
    }

    // ================================================================== material
    void ApplyMaterialSettings()
    {
        if (_mat == null) return;

        _mat.SetColor(ID_Color, shadowColor);
        _mat.SetFloat(ID_Falloff, edgeFalloff);
        _mat.SetFloat(ID_DitherScale, Mathf.Max(0.25f, ditherScale));
        _mat.SetFloat(ID_Opacity, opacity * _heightFade);

        Texture2D tex = null;
        switch (pattern)
        {
            case DitherPattern.Bayer2x2: tex = GetBayerTexture(2); break;
            case DitherPattern.Bayer8x8: tex = GetBayerTexture(8); break;
            case DitherPattern.Bayer16x16: tex = GetBayerTexture(16); break;
            case DitherPattern.CustomTexture:
                tex = customPattern;
                break;
        }

        if (tex != null)
        {
            if (pattern == DitherPattern.CustomTexture)
            {
                tex.filterMode = FilterMode.Point;
                tex.wrapMode = TextureWrapMode.Repeat;
            }
            _mat.SetTexture(ID_Pattern, tex);
            _mat.SetFloat(ID_PatternSize, tex.width);
            _mat.SetFloat(ID_UsePattern, 1f);
        }
        else
        {
            _mat.SetFloat(ID_UsePattern, 0f); // built-in Bayer 4x4 (also the fallback when Custom has no texture)
        }
    }

    // ================================================================== generated assets
    static Mesh GetQuad()
    {
        if (s_Quad != null) return s_Quad;

        Mesh m = new Mesh { name = "PS1 Blob Shadow Quad", hideFlags = HideFlags.HideAndDontSave };
        m.vertices = new[]
        {
            new Vector3(-0.5f, 0f, -0.5f),
            new Vector3(-0.5f, 0f,  0.5f),
            new Vector3( 0.5f, 0f,  0.5f),
            new Vector3( 0.5f, 0f, -0.5f),
        };
        m.uv = new[]
        {
            new Vector2(0f, 0f), new Vector2(0f, 1f), new Vector2(1f, 1f), new Vector2(1f, 0f)
        };
        m.normals = new[] { Vector3.up, Vector3.up, Vector3.up, Vector3.up };
        m.triangles = new[] { 0, 1, 2, 0, 2, 3 }; // clockwise seen from above -> faces up
        m.bounds = new Bounds(Vector3.zero, new Vector3(1f, 0.1f, 1f));
        s_Quad = m;
        return m;
    }

    static Texture2D GetBayerTexture(int n)
    {
        Texture2D cached;
        if (s_Bayer.TryGetValue(n, out cached) && cached != null) return cached;

        int[,] matrix = BuildBayer(n);
        Texture2D tex = new Texture2D(n, n, TextureFormat.RGBA32, false, true)
        {
            name = "PS1 Blob Bayer " + n + "x" + n,
            filterMode = FilterMode.Point,
            wrapMode = TextureWrapMode.Repeat,
            hideFlags = HideFlags.HideAndDontSave
        };

        Color32[] px = new Color32[n * n];
        float denom = n * n;
        for (int y = 0; y < n; y++)
        {
            for (int x = 0; x < n; x++)
            {
                byte v = (byte)Mathf.Clamp(Mathf.RoundToInt((matrix[y, x] + 0.5f) / denom * 255f), 0, 255);
                px[y * n + x] = new Color32(v, v, v, v);
            }
        }
        tex.SetPixels32(px);
        tex.Apply(false, true);

        s_Bayer[n] = tex;
        return tex;
    }

    static int[,] BuildBayer(int n)
    {
        if (n <= 2) return new[,] { { 0, 2 }, { 3, 1 } };

        int half = n / 2;
        int[,] h = BuildBayer(half);
        int[,] m = new int[n, n];
        for (int y = 0; y < half; y++)
        {
            for (int x = 0; x < half; x++)
            {
                int v = 4 * h[y, x];
                m[y, x] = v;
                m[y, x + half] = v + 2;
                m[y + half, x] = v + 3;
                m[y + half, x + half] = v + 1;
            }
        }
        return m;
    }

    // ================================================================== gizmos
    void OnDrawGizmosSelected()
    {
        Solution s;
        Solve(out s);

        Vector3 center = transform.position;
        Quaternion rot = s.frame;
        Gizmos.color = new Color(1f, 0.9f, 0.2f, 1f);

        if (s.hasGround)
        {
            rot = Quaternion.FromToRotation(Vector3.up, s.normal) * s.frame;
            center = s.point + s.normal * heightOffset;
            Gizmos.DrawLine(transform.position, s.point);
            Gizmos.color = new Color(0f, 1f, 1f, 1f);
        }

        DrawEllipse(center, rot, s.size);
    }

    static void DrawEllipse(Vector3 c, Quaternion rot, Vector2 size)
    {
        const int segments = 40;
        Vector3 prev = c + rot * new Vector3(size.x * 0.5f, 0f, 0f);
        for (int i = 1; i <= segments; i++)
        {
            float a = i * Mathf.PI * 2f / segments;
            Vector3 p = c + rot * new Vector3(Mathf.Cos(a) * size.x * 0.5f, 0f, Mathf.Sin(a) * size.y * 0.5f);
            Gizmos.DrawLine(prev, p);
            prev = p;
        }
    }
}

